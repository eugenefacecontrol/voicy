// Translate authored strings only, never interpolated user text or voice names.
function t(message, ...values) {
  const translate = text => uiLang === "ru" ? text : (uiEnglish[text] ?? text);
  if (typeof message === "string") return translate(message);
  return message.reduce((result, part, index) => result + translate(part) + (index < values.length ? values[index] : ""), "");
}

document.documentElement.lang = uiLang;
// Localize the static shell once, before app initialization inserts user content.
const uiWalker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
while (uiWalker.nextNode()) {
  const node = uiWalker.currentNode;
  if (node.parentElement.closest("script, style")) continue;
  const key = node.textContent.trim();
  if (Object.hasOwn(uiEnglish, key)) node.textContent = node.textContent.replace(key, t(key));
}
for (const element of document.querySelectorAll("*")) {
  for (const attribute of ["aria-label", "placeholder", "title", "content"]) {
    const value = element.getAttribute(attribute);
    if (value && Object.hasOwn(uiEnglish, value)) element.setAttribute(attribute, t(value));
  }
}
if (uiLang === "ru") document.querySelector(".brand").href = "?lang=ru";
